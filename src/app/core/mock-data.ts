const agGrant = (
  id: number,
  title: string,
  donor: string,
  amount: string,
  state: string,
  category: string,
  deadlineIn: number | null,
  postedAgo: number,
  type: NonNullable<GrantCardData['type']>,
  source: 'federal' | 'foundation',
  icon: string,
  tone: string,
  description: string,
  isNew = false,
): GrantCardData => ({
  id,
  title,
  donor,
  amount,
  state,
  category,
  deadline: deadlineIn === null ? '' : fromToday(deadlineIn),
  posted: fromToday(-postedAgo),
  type,
  source,
  isNew,
  description,
  icon,
  tone,
});

