export const getGrantDetail = (id: string): GrantDetail | null => {
  const fixed = MOCK_GRANT_DETAILS.find((d) => d.id === id);
  if (fixed) return fixed;

  const all = allGrantCards();
  const g = all.find((c) => String(c.id) === id);
  if (!g) return null;

  const others = all.filter((c) => c.id !== g.id);
  const sameState = others.filter((c) => c.state === g.state);
  const sameArea = others.filter((c) => c.category === g.category);

  const text = g.description ?? g.title;
  const type = g.type ?? 'Grant';
  const funder = g.source === 'federal' ? 'US federal agency' : 'private foundation';

  return {
    id: String(g.id),
    title: g.title,
    shortTitle: g.title,
    intro: `${text} ${g.donor} invites proposals that strengthen communities.`,
    posted: g.posted ?? '',
    deadline: g.deadline,
    grantSize: g.amount,
    duration: 'Not Mentioned',
    donor: g.donor,
    category: type,
    overview: [
      para(
        `${text} ${g.donor} invites proposals from eligible applicants. Review the details below and visit the official website for the complete guidelines.`,
      ),
      head('About the Funder'),
      para(
        `${g.donor} is a ${funder} that supports work in ${g.category.toLowerCase()}. This ${type.toLowerCase()} is offered to applicants based in ${g.state}.`,
      ),
      head('Funding Details'),
      bullets([
        `Grant size: ${g.amount}`,
        `Funding type: ${type}`,
        `Focus area: ${g.category}`,
        `Location: ${g.state}`,
      ]),
      head('Eligibility Criteria'),
      bullets(g.eligibility?.length ? g.eligibility : DEFAULT_ELIGIBILITY),
      head('How to Apply'),
      bullets([
        'Read the full guidelines on the official website.',
        'Prepare your project summary, budget and supporting documents.',
        'Submit your application before the deadline.',
        'Keep a copy of the confirmation for your records.',
      ]),
      head('Key Dates'),
      bullets([
        `Posted: ${fmtDate(g.posted ?? '') || 'Not available'}`,
        `Deadline: ${g.deadline ? fmtDate(g.deadline) : 'Ongoing (rolling basis)'}`,
      ]),
      ...(g.donor ? [moreLink('For more information, visit ', g.donor, '', '.')] : []),
    ],
    focusAreas: [g.category, type],
    counties: ['All Counties'],
    states: [g.state],
    websiteUrl: '',
    // Pehle same state / same area wale, kam pade to baaki se bhar do
    relatedState: [...sameState, ...others.filter((c) => c.state !== g.state)]
      .slice(0, 8)
      .map((c) => toRelated(c, c.state)),
    relatedThematic: [...sameArea, ...others.filter((c) => c.category !== g.category)]
      .slice(0, 8)
      .map((c) => toRelated(c, c.category)),
  };
};
